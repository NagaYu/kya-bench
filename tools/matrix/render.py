"""Render docs/conformance-matrix.md from docs/conformance-matrix.json."""

from __future__ import annotations

import json
import sys
from pathlib import Path

HEADER = """# Conformance matrix: KYA Bench vs reference implementations

How KYA Bench's expected verdicts compare with what each protocol's own reference
implementation does on the same vectors. Generated by `tools/matrix/run_matrix.py`;
do not edit by hand.

## Reproduce

The matrix needs the reference implementations, so it is **not** part of `tools/ci.sh`.
Everything below runs offline once the clones and dependencies are in place.

```bash
mkdir -p ../kya-refs && cd ../kya-refs
git clone https://github.com/agent-intent/verifiable-intent && git -C verifiable-intent checkout 356c29635f1c44df7de02edb58699ca9f29bece6
git clone https://github.com/google-agentic-commerce/AP2 && git -C AP2 checkout e1ea56db72a6385bce3e5c1112b3a56ce60acb43
git clone https://github.com/visa/trusted-agent-protocol && git -C trusted-agent-protocol checkout 16d59bdf3f8a542bc538d0962edbb80ea30a02af
cd -
python3 -m venv .matrix-venv
.matrix-venv/bin/pip install "cryptography==46.0.5" "jwcrypto==1.5.6" "pydantic==2.12.5" "sd-jwt==0.10.4"
.matrix-venv/bin/python tools/matrix/run_matrix.py --refs ../kya-refs && python3 tools/matrix/render.py
```

Node.js (tested with 22) runs the TAP reference proxy. `run_matrix.py` refuses to run if
a clone is not at its pinned commit. No npm install is needed: the harness stubs the
proxy's express/axios/dotenv imports and calls its `verifySignature` directly.

## How to read it

- **agree**: the reference reaches KYA's expected verdict. **incidental** agreements are
  rejections the reference made for a different, early reason (see VI-M1, TAP-M1): same
  verdict, different cause.
- **diverge / verdict**: KYA expects accept or reject and the reference does the opposite.
- **diverge / spec_gap**: KYA expects `indeterminate` (the spec leaves the case undefined)
  and the reference decides. These show how the reference resolves each gap.
- **not_runnable**: the vector cannot be expressed in the reference's input model. Counted,
  with reasons, rather than forced through.
- A reference exception counts as a rejection; the raw outcome is kept in the JSON.
"""


def render(doc: dict) -> str:
    out = [HEADER, "## Summary\n",
           "| Protocol | Reference | Vectors | Runnable | Agree (incidental) | Diverge: verdict | "
           "Diverge: spec gap | Not runnable |",
           "|---|---|---|---|---|---|---|---|"]
    for proto, s in doc["summary"].items():
        out.append(f"| {proto} | {s['reference']} | {s['vectors']} | {s['runnable']} | {s['agree']} "
                   f"({s['agree_incidental']}) | {s['diverge_verdict']} | {s['diverge_spec_gap']} | "
                   f"{s['not_runnable']} |")
    out.append("\nNot-runnable reasons:\n")
    for proto, s in doc["summary"].items():
        for reason, n in s["not_runnable_reasons"].items():
            out.append(f"- **{proto}** ({n}): {reason}")
    out.append("\n## Findings\n")
    for fid, f in doc["findings"].items():
        ids = [r["id"] for r in doc["rows"] if r.get("finding") == fid]
        out.append(f"### {fid}: {f['title']}\n")
        out.append(f"- **Reference:** {f['reference']}")
        out.append(f"- **Spec:** {f['spec']}")
        out.append(f"- **Assessment:** {f['assessment']}")
        if ids:
            out.append(f"- **Vectors ({len(ids)}):** " + ", ".join(f"`{i}`" for i in ids))
        out.append("")
    out.append("## Divergences\n")
    out.append("| Protocol | Vector | KYA expected | Reference | Kind | Finding | Reference said |")
    out.append("|---|---|---|---|---|---|---|")
    for r in doc["rows"]:
        if r["status"] == "diverge":
            said = r["reference_detail"].splitlines()[0][:110].replace("|", "\\\\|")
            out.append(f"| {r['protocol']} | `{r['id']}` | {r['kya_expected']} | {r['reference']} | {r['kind']} | "
                       f"{r.get('finding') or ''} | {said} |")
    out.append("\n## All vectors\n")
    out.append("| Protocol | Vector | KYA expected | Reference | Status |")
    out.append("|---|---|---|---|---|")
    for r in doc["rows"]:
        status = r["status"] + (" (incidental)" if r.get("incidental") else "")
        out.append(f"| {r['protocol']} | `{r['id']}` | {r['kya_expected']} | {r.get('reference', '—')} | {status} |")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    docs = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parents[2] / "docs"
    doc = json.loads((docs / "conformance-matrix.json").read_text())
    (docs / "conformance-matrix.md").write_text(render(doc))
